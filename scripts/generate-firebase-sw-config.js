// Generates public/firebase-sw-config.js with Firebase client config embedded.
// Runs as a prebuild/predev step so the service worker can self-initialize
// for background push notifications (no page required).
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

// Parse .dev.vars (Miniflare format) for local development
const devVars = {};
const devVarsPath = join(root, ".dev.vars");
if (existsSync(devVarsPath)) {
  for (const line of readFileSync(devVarsPath, "utf-8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    let value = trimmed.slice(eqIdx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    devVars[key] = value;
  }
}

const get = (name) => devVars[name] ?? process.env[name] ?? "";

const config = {
  apiKey: get("VITE_FIREBASE_API_KEY"),
  authDomain: get("VITE_FIREBASE_AUTH_DOMAIN"),
  projectId: get("VITE_FIREBASE_PROJECT_ID"),
  storageBucket: get("VITE_FIREBASE_STORAGE_BUCKET"),
  messagingSenderId: get("VITE_FIREBASE_MESSAGING_SENDER_ID"),
  appId: get("VITE_FIREBASE_APP_ID"),
};

const output = `// Auto-generated by scripts/generate-firebase-sw-config.js — do not edit.
// Re-generated on every \`npm run dev\` and \`npm run build\`.
self.FIREBASE_CONFIG = {
  apiKey: "${config.apiKey}",
  authDomain: "${config.authDomain}",
  projectId: "${config.projectId}",
  storageBucket: "${config.storageBucket}",
  messagingSenderId: "${config.messagingSenderId}",
  appId: "${config.appId}",
};
`;

writeFileSync(join(root, "public", "firebase-sw-config.js"), output, "utf-8");
console.log("✓ Generated public/firebase-sw-config.js");
